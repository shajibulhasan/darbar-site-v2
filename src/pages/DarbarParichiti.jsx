function Inline({ text }) {
  return text.split(/([\u0600-\u06FF]+(?:\s+[\u0600-\u06FF]+)*)/).map((part, i) =>
    i % 2 ? <span className="ar-inline" lang="ar" dir="rtl" key={i}>{part}</span> : part
  );
}

